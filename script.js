const escapeHtml = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");

const imageAlt = (run, image) => `${image.title} from the Rapty Paints ${run.title} run.`;
const responsiveWidths = [360, 900, 1600];

function optimizedImageSrc(src, width = 900) {
  const match = src.match(/^imgs\/(.+)\.(?:jpe?g|png)$/i);
  return match ? `imgs/optimized/${match[1]}-${width}.webp` : src;
}

function responsiveSrcset(src) {
  return responsiveWidths
    .map((width) => `${optimizedImageSrc(src, width)} ${width}w`)
    .join(", ");
}

function responsiveImageAttrs(src, alt, sizes, loading = "lazy") {
  return `src="${escapeHtml(optimizedImageSrc(src, 900))}" srcset="${escapeHtml(responsiveSrcset(src))}" sizes="${escapeHtml(sizes)}" alt="${escapeHtml(alt)}" loading="${loading}" decoding="async"`;
}

function setResponsiveImage(imageElement, src, alt, sizes) {
  imageElement.src = optimizedImageSrc(src, 900);
  imageElement.srcset = responsiveSrcset(src);
  imageElement.sizes = sizes;
  imageElement.alt = alt;
  imageElement.loading = "lazy";
  imageElement.decoding = "async";
}

