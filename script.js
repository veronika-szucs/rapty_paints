function brushSeed(text) {
  let seed = 0;
  for (let index = 0; index < text.length; index += 1) {
    seed = (seed * 31 + text.charCodeAt(index)) % 9973;
  }
  return seed;
}

function seededRandom(seed) {
  let value = seed;
  return () => {
    value = (value * 9301 + 49297) % 233280;
    return value / 233280;
  };
}

function drawBrushLines() {
  document.querySelectorAll("[data-brush]").forEach((target) => {
    if (target.querySelector(".brush-svg")) return;
    target.classList.add("brush-target");
    const random = seededRandom(brushSeed(target.textContent || ""));
    const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    svg.setAttribute("class", `brush-svg brush-${target.dataset.brush || "rose"}`);
    svg.setAttribute("viewBox", "0 0 100 14");
    svg.setAttribute("preserveAspectRatio", "none");
    svg.setAttribute("aria-hidden", "true");

    for (let line = 0; line < 3; line += 1) {
      const y = 8 + line * 1.4 + (random() - 0.5) * 2;
      const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
      const c1x = 22 + random() * 11;
      const c2x = 58 + random() * 12;
      const c1y = y + (random() - 0.5) * 7;
      const c2y = y + (random() - 0.5) * 7;
      path.setAttribute("d", `M 1 ${y.toFixed(2)} C ${c1x.toFixed(2)} ${c1y.toFixed(2)}, ${c2x.toFixed(2)} ${c2y.toFixed(2)}, 99 ${(y + (random() - 0.5) * 3).toFixed(2)}`);
      path.setAttribute("pathLength", "100");
      svg.append(path);
    }

    target.append(svg);
  });
}

